/**
 * Reads perf/thresholds.json and emits perf/k6/lib/thresholds.js for k6 imports.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PERF_DIR = join(__dirname, '..');
const THRESHOLDS_PATH = join(PERF_DIR, 'thresholds.json');
const OUTPUT_PATH = join(PERF_DIR, 'k6', 'lib', 'thresholds.js');

const thresholds = JSON.parse(readFileSync(THRESHOLDS_PATH, 'utf8'));

function activeProfileName() {
  if (process.env.PERF_CI === '1') return 'ci';
  return process.env.PERF_PROFILE ?? 'local';
}

function mergeProfile(base, profileOverrides) {
  const merged = { ...base };
  for (const [key, value] of Object.entries(profileOverrides ?? {})) {
    if (
      value &&
      typeof value === 'object' &&
      !Array.isArray(value) &&
      merged[key] &&
      typeof merged[key] === 'object' &&
      !Array.isArray(merged[key])
    ) {
      merged[key] = { ...merged[key], ...value };
    } else {
      merged[key] = value;
    }
  }
  return merged;
}

const profileName = activeProfileName();
const effectiveThresholds = mergeProfile(
  thresholds,
  thresholds.profiles?.[profileName] ?? {},
);

function buildK6Thresholds(t) {
  const out = {};

  // review-submit
  out.reviewSubmit = {
    http_req_failed: [`rate<${t.reviewSubmit.httpReqFailedRate}`],
    'http_req_duration{endpoint:review_submit}': [
      `p(95)<${t.reviewSubmit.httpReqDurationP95Ms}`,
      `p(99)<${t.reviewSubmit.httpReqDurationP99Ms}`,
    ],
    'http_req_duration{endpoint:review_read_detail}': [
      `p(95)<${t.reviewSubmit.httpReqDurationP95Ms}`,
    ],
    checks: [`rate>${t.reviewSubmit.checksRateMin}`],
  };

  // email-pipeline
  out.emailPipeline = {
    email_pipeline_drain_seconds: [`max<${t.emailPipeline.drainSecondsMax}`],
    email_pipeline_throughput_per_sec: [
      `min>${t.emailPipeline.minThroughputPerSecond}`,
    ],
  };

  // generic HTTP suites with endpoint tags (all now use ramping-vus)
  const httpSuites = [
    ['editorQueue', 'editor_queue'],
    ['reviewerInbox', 'reviewer_inbox'],
    ['authLogin', 'auth_login'],
    ['publicSearch', 'public_search'],
    ['notifications', 'notifications'],
    ['submissionDetail', 'submission_detail'],
    ['fileUpload', 'file_upload'],
    ['auditStress', 'audit_stress'],
  ];

  for (const [key, tag] of httpSuites) {
    const cfg = t[key];
    if (!cfg) continue;
    out[key] = {
      http_req_failed: [`rate<${cfg.httpReqFailedRate}`],
      [`http_req_duration{endpoint:${tag}}`]: [
        `p(95)<${cfg.httpReqDurationP95Ms}`,
      ],
      checks: ['rate>0.99'],
    };
  }

  // write-read-concurrent: separate thresholds for read and write endpoint tags
  if (t.writeReadConcurrent) {
    const wrc = t.writeReadConcurrent;
    out.writeReadConcurrent = {
      http_req_failed: [`rate<${wrc.httpReqFailedRate}`],
      'http_req_duration{endpoint:wrc_read}': [
        `p(95)<${wrc.httpReqDurationP95Ms}`,
      ],
      'http_req_duration{endpoint:wrc_write}': [
        `p(95)<${wrc.writeDurationP95Ms}`,
      ],
      checks: ['rate>0.99'],
    };
  }

  // pool-stress: includes recovery check after pool exhaustion
  out.poolStress = {
    http_req_failed: [`rate<${t.poolStress.httpReqFailedRate}`],
    http_req_duration: [`max<${t.poolStress.httpReqDurationMaxMs}`],
    'http_req_duration{endpoint:pool_recovery}': [
      `p(95)<${t.poolStress.recoveryP95Ms ?? 3000}`,
    ],
  };

  // soak: enforce both error rate and absolute P95 latency
  out.soak = {
    http_req_failed: [`rate<${t.soak.httpReqFailedRate}`],
    'http_req_duration{endpoint:soak}': [
      `p(95)<${t.soak.httpReqDurationP95Ms ?? 2000}`,
    ],
  };

  return out;
}

const k6Thresholds = buildK6Thresholds(effectiveThresholds);

const raw = JSON.stringify(effectiveThresholds, null, 2);
const k6Raw = JSON.stringify(k6Thresholds, null, 2);

const content = `// AUTO-GENERATED by perf/scripts/generate-k6-thresholds.mjs — do not edit.
export const thresholdsConfig = ${raw};

export const k6Thresholds = ${k6Raw};

export function suiteThresholds(suiteName) {
  return k6Thresholds[suiteName] ?? {};
}

export function suiteConfig(suiteName) {
  return thresholdsConfig[suiteName] ?? {};
}

export const activeProfile = ${JSON.stringify(profileName)};
`;

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, content);
console.log(`Wrote ${OUTPUT_PATH}`);
